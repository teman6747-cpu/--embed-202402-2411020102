/* USER CODE BEGIN PV */
uint8_t KeyScan(void)
{
    uint8_t col;
    for(col = 0; col < 3; col++)
    {
        // 全部列PE4 PE5 PE6拉高
        GPIOE->ODR |= (1<<4) | (1<<5) | (1<<6);
        // 拉低当前扫描列
        GPIOE->ODR &= ~(1 << (4 + col));
        HAL_Delay(10);

        uint8_t row = GPIOE->IDR & 0x0F;
        if(row != 0x0F)
        {
            switch(row)
            {
                case 0x0E: return col*4 + 1;  //PE0 → K1
                case 0x0D: return col*4 + 2;  //PE1 → K2
                case 0x0B: return col*4 + 3;  //PE2 → K3
                case 0x07: return col*4 + 4;  //PE3 → K4
            }
            while( (GPIOE->IDR & 0x0F) != 0x0F ); //等待松手
        }
    }
    return 0;
}
